// Walks the real flow on :3300: Today → load → Find a buyer → live → deal → chat rule change.
import { chromium } from "/home/momoh_mustapha/projects/lifeline/node_modules/playwright-core/index.mjs";
const out = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome" });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
p.on("response", (r) => r.status() >= 500 && errors.push(`${r.status()} ${r.url()}`));
const shot = (n) => p.screenshot({ path: `${out}/flow-${n}.png`, fullPage: true });
const t0 = Date.now();
const log = (m) => console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s ${m}`);

await p.goto("http://localhost:3300/today", { waitUntil: "networkidle" });
await p.waitForSelector(".b-sch-event");
await shot("1-today");
await p.click("text=Open");
await p.waitForURL(/\/loads\//);
const loadUrl = p.url();
log("load " + loadUrl);
await p.waitForTimeout(800);
await shot("2-ready");
const pdf = await p.request.get(new URL(await p.getAttribute("a[href^='/api/files/']", "href"), loadUrl).toString());
log(`pdf ${pdf.status()} ${pdf.headers()["content-type"]} ${(await pdf.body()).length} bytes`);
await p.click("button:has-text('Find a buyer')");
await p.waitForTimeout(14000);
await shot("3-live");
log("live shot");
await p.waitForSelector("text=Approve and hold payment", { timeout: 150000 });
log("deal ready");
await p.waitForTimeout(1500);
await shot("4-deal");
const dealBuyer = await p.textContent("text=/will take all/");
log("agent: " + dealBuyer?.slice(0, 160));
await p.fill("input[aria-label='Message your agent']", "Why did FreshMart reject the load?");
await p.click("button[aria-label='Send']");
await p.waitForSelector("text=Your agent is thinking…", { state: "detached", timeout: 60000 });
await p.waitForTimeout(1000);
log("answered");
await shot("5-chat");
console.log(errors.length ? "ERRORS " + JSON.stringify(errors.slice(0, 5)) : "no errors");
await b.close();
