// /architecture (the map explorer): map, a journey mid-play, trust, decisions, and a phone.
import { chromium } from "/home/momoh_mustapha/projects/lifeline/node_modules/playwright-core/index.mjs";
const out = process.argv[2];
const BASE = process.env.BASE ?? "http://localhost:3300";
const b = await chromium.launch({ executablePath: process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
await p.goto(`${BASE}/architecture`, { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/arch-map.png` });
await p.click("button:has-text('Your agent')");
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/arch-node.png` });
await p.keyboard.press("Escape");
await p.click("nav button:has-text('Journeys')");
await p.waitForTimeout(2600 * 7 + 500);
await p.screenshot({ path: `${out}/arch-journey.png` });
await p.click("nav button:has-text('Trust')");
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/arch-trust.png` });
await p.click("nav button:has-text('Decisions')");
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/arch-decisions.png`, fullPage: true });
const ph = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })).newPage();
await ph.goto(`${BASE}/architecture`, { waitUntil: "networkidle" });
await ph.waitForTimeout(800);
await ph.screenshot({ path: `${out}/arch-phone.png`, fullPage: true });
console.log("phone width", await ph.evaluate(() => document.documentElement.scrollWidth), errors.length ? "ERRORS " + JSON.stringify(errors.slice(0, 3)) : "no page errors");
await b.close();
