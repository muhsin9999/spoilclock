// The unhappy path on its own: negotiate → approve → the new dock rejects → PayPal voids → try the others.
import { chromium } from "/home/momoh_mustapha/projects/lifeline/node_modules/playwright-core/index.mjs";
const [out] = process.argv.slice(2);
const BASE = process.env.BASE ?? "http://localhost:3300";
const b = await chromium.launch({ executablePath: process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome" });
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
p.on("dialog", (d) => d.accept());
const t0 = Date.now();
const log = (m) => console.log(`${((Date.now() - t0) / 1000).toFixed(0)}s ${m}`);
await p.goto(`${BASE}/today`, { waitUntil: "networkidle" });
await p.click("a:has-text('Truck 14')"); await p.waitForURL(/loads/); await p.waitForLoadState("networkidle");
await p.screenshot({ path: `${out}/void-0-ready.png`, fullPage: true });
await p.click("button:has-text('Find a buyer')");
await p.waitForSelector("text=Approve and hold payment", { timeout: 240000 }); log("deal");
await p.screenshot({ path: `${out}/void-1-deal.png`, fullPage: true });
await p.click("button:has-text('Approve and hold payment')");
await p.waitForSelector("text=Open the dock check", { timeout: 60000 }); log("held");
const href = await p.getAttribute("text=Open the dock check", "href");
const phone = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const d = await phone.newPage(); d.on("dialog", (x) => x.accept());
await d.goto(BASE + href, { waitUntil: "networkidle" });
await d.click("button:has-text('Reject load')");
await d.waitForSelector("text=Rejected · hold released", { timeout: 60000 }); log("voided on the dock");
await d.screenshot({ path: `${out}/void-2-dock.png`, fullPage: true });
await p.reload({ waitUntil: "networkidle" });
await p.waitForSelector("text=/Rejected at the dock · hold released/", { timeout: 30000 });
log(`try again visible: ${await p.isVisible("button:has-text('Try again')")}`);
await p.screenshot({ path: `${out}/void-3-load.png`, fullPage: true });
await p.click("button:has-text('Try again')");
await p.waitForSelector("text=Approve and hold payment", { timeout: 240000 });
log("second deal: " + (await p.textContent("text=/will take all/")).slice(0, 90));
await p.screenshot({ path: `${out}/void-4-second-deal.png`, fullPage: true });
await p.setViewportSize({ width: 390, height: 844 });
await p.reload({ waitUntil: "networkidle" });
await p.screenshot({ path: `${out}/void-5-phone.png`, fullPage: true });
await b.close();
